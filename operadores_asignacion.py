#ASIGNACION =

x = 5
print(x)

# asignacion con suma
x = x + 2
x += 2
print(x)

# asignacion con resta
x = x - 3
x -= 3
print(x)

# asignacion con multiplicacion
x = x * 4
x *= 4
print(x)

# asignacion con division
x = x / 5
x /= 5
print(x)

# asignacion con division entera
x = x // 2
x //= 2
print(x)

# asignacion con modulo
x = x % 2
x %= 2
print(x)

# asignacion con potencia
x = x ** 2
x **= 2
print(x)

