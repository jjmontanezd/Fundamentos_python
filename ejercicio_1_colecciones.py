# EJERCICIO 1: PRODUCTO ESCALAR DE DOS VECTORES

# Almacenar los vectores en dos tuplas
vector1 = (1, 2, 3)
vector2 = (-1, 0, 2)

# Calcular el producto escalar
resultado = (vector1[0] * vector2[0]) + (vector1[1] * vector2[1]) + (vector1[2] * vector2[2])

# Mostrar los vectores y el resultado
print("EJERCICIO 1: PRODUCTO ESCALAR")
print("Primer vector:", vector1)
print("Segundo vector:", vector2)
print("El producto escalar es:", resultado)


# EJERCICIO 2: MENOR Y MAYOR PRECIO

# Almacenar los precios en una lista
precios = [50, 75, 46, 22, 80, 65, 8]

# Encontrar el menor y el mayor precio
menor = min(precios)
mayor = max(precios)

# Mostrar los resultados
print("\nEJERCICIO 2: MENOR Y MAYOR PRECIO")
print("Lista de precios:", precios)
print("El menor precio es:", menor)
print("El mayor precio es:", mayor)